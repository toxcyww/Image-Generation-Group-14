import math
import cv2
import numpy as np
import torch
from torch.nn import functional as F
from runtime import tensor, to_rgb, pose_degrees, cos

def patch_mask(target, face):
    """Gaussian support at target eyes/mouth; no source identity pixels."""
    points = np.asarray(face[4:14]).reshape(5, 2)
    eye_distance = float(np.linalg.norm(points[0] - points[1]))
    yy, xx = np.mgrid[:256, :256].astype(np.float32)
    mask = np.zeros((256, 256), np.float32)
    for point in points[:2]:
        mask += 2 * np.exp(-.5 * (((xx-point[0])/(eye_distance*.30))**2 + ((yy-point[1])/(eye_distance*.16))**2))
    mouth = points[3:5].mean(0)
    mask += np.exp(-.5 * (((xx-mouth[0])/(eye_distance*.45))**2 + ((yy-mouth[1])/(eye_distance*.25))**2))
    return torch.from_numpy(mask)[None, None].to(target)


class JointLoss:
    @staticmethod
    def small(raw):
        # Match final PNG's clipping before reduction; quantization is deferred.
        return F.interpolate(raw.clamp(-1, 1), (256, 256), mode='area')

    def new_losses(self, raw, w, w0, ctx, target, mask, supervised):
        x = self.small(raw)
        attrs = self.attr(x, ctx['roi'])
        expr = F.mse_loss(attrs['expression'], ctx['attr']['expression'])
        rot = F.mse_loss(attrs['rotation'], ctx['attr']['rotation'])
        rot_tol = 4 * (1 - math.cos(math.radians(5))) / 9
        nonid = F.relu(expr-.15**2) + F.relu(rot-rot_tol)
        identity = (self.arc(x, ctx['grid']) * ctx['arc']).sum()
        margin = F.relu(identity-.25)
        zeros = x.new_zeros(())
        mse = F.mse_loss(x, target) if supervised else zeros
        lp = self.lpips(x, target).mean() if supervised else zeros
        parts = (((x-target).square()*mask).sum()/(3*mask.sum())) if supervised else zeros
        color = F.mse_loss(F.avg_pool2d(x, 16), F.avg_pool2d(target, 16)) if supervised else zeros
        regular = F.mse_loss(w, w0)
        outside = F.relu(raw.abs()-1).square().mean()
        total = .5*nonid+2*margin+mse+.8*lp+4*parts+2*color+.1*regular+outside
        return {'total': total, 'expression_mse': expr, 'rotation_mse': rot,
            'nonid_hinge': nonid, 'arcface_cosine': identity, 'identity_margin': margin,
            'target_mse': mse, 'target_lpips': lp, 'target_parts_mse': parts,
            'target_color_mse': color, 'latent_mse': regular, 'range_penalty': outside}

    @torch.no_grad()
    def metrics(self, rgb, ctx, target=None, independent=True):
        x = tensor(rgb)
        attrs = self.attr(x, ctx['roi'])
        arc = float((self.arc(x, ctx['grid']) * ctx['arc']).sum())
        small = to_rgb(x)
        face = self.vision.detect(small)
        gray = cv2.cvtColor(small, cv2.COLOR_RGB2GRAY)
        result = {'arcface_cosine_fixed': arc,
                  'expression_mae': float((attrs['expression'] - ctx['attr']['expression']).abs().mean()),
                  'pose_degrees': pose_degrees(attrs['rotation'], ctx['attr']['rotation']),
                  'face_detected': face is not None,
                  'detection_confidence': float(face[-1]) if face is not None else 0.,
                  'laplacian_variance': float(cv2.Laplacian(gray, cv2.CV_32F).var()),
                  'clipped_pixel_fraction': float(((small <= 1) | (small >= 254)).mean()),
                  'lpips_to_source': float(self.lpips(x, ctx['src']).mean())}
        if target is not None:
            result['lpips_to_target'] = float(self.lpips(x, target).mean())
            result['mse_to_target'] = float(F.mse_loss(x, target))
        if face is not None:
            redetected = self.attr(x, self.vision.roi(face))
            result['expression_mae_redetected'] = float((redetected['expression'] - ctx['attr']['expression']).abs().mean())
            result['pose_degrees_redetected'] = pose_degrees(redetected['rotation'], ctx['attr']['rotation'])
            result['arcface_cosine_redetected'] = float((self.arc(x, self.vision.grid(face)) * ctx['arc']).sum())
        if independent:
            result['sface_cosine'] = cos(self.vision.independent_feature(rgb), ctx['sface'])
            result['facenet_cosine_fixed'] = cos(self.facenet.feature(rgb, ctx['face']), ctx['facenet'])
            result['facenet_cosine_redetected'] = cos(self.facenet.feature(rgb, face), ctx['facenet']) if face is not None else None
        return result


    def nonid_losses(self, raw, w, wrandom, z0, roi):
        # Generation sees only Z0, independent seed/ROI and frozen models.
        # No source image, source w0, ArcFace embedding or X' enters this path.
        attrs = self.attr(self.small(raw), roi)
        expr = F.mse_loss(attrs['expression'], z0['expression'])
        rot = F.mse_loss(attrs['rotation'], z0['rotation'])
        prior = F.mse_loss(w, wrandom)
        outside = F.relu(raw.abs()-1).square().mean()
        return {'total': 5*expr+20*rot+.2*prior+outside,
                'expression_mse': expr, 'rotation_mse': rot, 'latent_mse': prior, 'range_penalty': outside}
